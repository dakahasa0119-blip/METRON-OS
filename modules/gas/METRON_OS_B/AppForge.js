/**
 * 排出APPを生成するメイン関数
 * AppForge UI から呼ばれる
 */
function generateApp(appName, templateLevel, mode) {

  // 1. 新しいスプレッドシートを生成
  const ss = SpreadsheetApp.create(`${appName} - METRON APP`);
  const ssId = ss.getId();

  // 2. テンプレートを読み込む（TemplateLibrary から）
  const TEMPLATE_CORE         = getTemplate("TEMPLATE_CORE");
  const TEMPLATE_DATA         = getTemplate("TEMPLATE_DATA");
  const TEMPLATE_CSS          = getTemplate("TEMPLATE_CSS");
  const TEMPLATE_INTEGRATION  = getTemplate("TEMPLATE_INTEGRATION");
  const TEMPLATE_STANDALONE   = getTemplate("TEMPLATE_STANDALONE");

  // ★ UI はテンプレートではなく「母艦の UI_Fields から自動生成」
  const GENERATED_UI = buildUI();

  // 3. 排出APPにファイルを書き込む
  writeTemplateFile(ss, "App_Config.gs", buildConfig(appName, templateLevel, mode));
  writeTemplateFile(ss, "App_Core.gs", TEMPLATE_CORE);
  writeTemplateFile(ss, "App_Data.gs", TEMPLATE_DATA);
  writeTemplateFile(ss, "App_Integration.gs", TEMPLATE_INTEGRATION);
  writeTemplateFile(ss, "App_Standalone.gs", TEMPLATE_STANDALONE);

  // ★ 自動生成された UI を書き込む
  writeTemplateFile(ss, "App_UI.html", GENERATED_UI);

  writeTemplateFile(ss, "App_Styles.css", TEMPLATE_CSS);

  // 4. Connected Mode の場合は母艦の App_Registry に登録
  if (mode === "CONNECTED") {
    registerAppToMotherShip(appName, ssId, templateLevel, mode);
  }

  // 5. 生成したアプリのURLを返す
  return ss.getUrl();
}



/**
 * スクリプトファイルを排出APPに書き込む
 * （Apps Script の Drive API を使わず、プロジェクトAPIで直接作成）
 */
function writeTemplateFile(ss, name, content) {
  const project = AppsScriptProject.open(ss);
  project.createFile(name, content);
}



/**
 * App_Config.gs の内容を生成する
 * （排出APPの心臓部を動的に作る）
 */
function buildConfig(appName, templateLevel, mode) {

  const motherShipId = SpreadsheetApp.getActive().getId();
  const logoBase64 = getMotherShipLogo();
  const version = getTemplateVersion();

  // バッククォート内に危険文字が入らないように JSON.stringify を使用
  return [
    "/**",
    " * App_Config.gs（自動生成）",
    " * 排出APPの中核設定",
    " */",
    "",
    `const APP_NAME = ${JSON.stringify(appName)};`,
    `const APP_DESCRIPTION = "Generated by METRON OS";`,
    `const TEMPLATE_LEVEL = ${templateLevel};`,
    `const APP_THEME = "LIGHT";`,
    "",
    `const APP_LOGO_BASE64 = ${JSON.stringify(logoBase64)};`,
    "",
    `const METRON_MODE = ${JSON.stringify(mode)};`,
    `const MOTHERSHIP_ID = ${JSON.stringify(motherShipId)};`,
    "",
    "let APP_INITIALIZED = false;",
    "",
    `const SETTINGS_SHEET = "Settings";`,
    `const DATA_SHEET = "Data";`,
    `const LOG_SHEET = "Log";`,
    `const DASHBOARD_SHEET = "Dashboard";`,
    "",
    `const TEMPLATE_VERSION = ${version};`,
    ""
  ].join("\n");
}
/**
 * UI_Fields から UI を自動生成する
 */
function buildUI() {
  const fields = getUIFields(); // 母艦から UI 定義を取得

  let html = `
<!DOCTYPE html>
<html>
<head>
  <base target="_top">
  <link rel="stylesheet" href="App_Styles.css">
</head>
<body>
  <div id="app-container">
    <h2>${"<?= APP_NAME ?>"}</h2>
    <form id="dynamic-form">
  `;

  fields.forEach(f => {
    html += generateFieldHTML(f);
  });

  html += `
      <button type="button" onclick="saveData()">保存</button>
    </form>
  </div>

  <script src="App_Core.js"></script>
  <script src="App_Data.js"></script>
  <script src="App_Integration.js"></script>
  <script src="App_Standalone.js"></script>
</body>
</html>
  `;

  return html;
}
/**
 * フィールド定義から HTML を生成
 */
function generateFieldHTML(f) {
  const required = f.required ? "required" : "";

  switch (f.type) {
    case "text":
      return `
        <div class="field">
          <label>${f.label}</label>
          <input type="text" id="${f.field_key}" ${required}>
        </div>
      `;

    case "number":
      return `
        <div class="field">
          <label>${f.label}</label>
          <input type="number" id="${f.field_key}" ${required}>
        </div>
      `;

    case "textarea":
      return `
        <div class="field">
          <label>${f.label}</label>
          <textarea id="${f.field_key}" ${required}></textarea>
        </div>
      `;

    case "select":
      const options = f.options.map(o => `<option value="${o}">${o}</option>`).join("");
      return `
        <div class="field">
          <label>${f.label}</label>
          <select id="${f.field_key}" ${required}>
            ${options}
          </select>
        </div>
      `;

    default:
      return "";
  }
}
/**
 * UI_Fields から UI を完全自動生成する
 */
function buildUI() {
  const fields = getUIFields(); // 母艦から取得

  let html = `
<!DOCTYPE html>
<html>
<head>
  <base target="_top">
  <link rel="stylesheet" href="App_Styles.css">
</head>
<body>

  <div class="header">
    <img src="data:image/png;base64,<?= config.logo ?>" class="logo">
    <div class="app-title"><?= config.name ?></div>
    <div class="mode-badge <?= mode === 'CONNECTED' ? 'connected' : 'standalone' ?>">
      <?= mode === 'CONNECTED' ? '母艦連携' : '独立モード' ?>
    </div>
  </div>

  <div id="form-area">
    <h2>入力フォーム</h2>
    <form id="dynamic-form">
  `;

  fields.forEach(f => {
    html += generateFieldHTML(f);
  });

  html += `
      <button type="button" onclick="saveData()">保存</button>
    </form>
  </div>

  <div id="list-area">
    <h2>データ一覧</h2>
    <div id="data-list"></div>
  </div>

  <script>
    // UI_Fields を取得
    google.script.run.withSuccessHandler(fields => {
      window.UI_FIELDS = fields;
      loadData();
    }).getUIFieldsLocal();

    // 保存
    function saveData() {
      const fields = window.UI_FIELDS;
      const formData = {};

      fields.forEach(f => {
        formData[f.field_key] = document.getElementById(f.field_key).value;
      });

      google.script.run.withSuccessHandler(() => {
        alert("保存しました");
        loadData();
      }).saveDataDynamic(formData);
    }

    // 読み込み
    function loadData() {
      google.script.run.withSuccessHandler(rows => {
        const container = document.getElementById("data-list");
        container.innerHTML = "";

        rows.forEach(r => {
          const div = document.createElement("div");
          div.className = "card";

          let title = "";
          if (window.UI_FIELDS.length > 0) {
            title = r[window.UI_FIELDS[0].field_key];
          }

          div.innerHTML = \`
            <div class="card-title">\${title}</div>
            <button onclick="deleteRecord('\${r.id}')">削除</button>
          \`;

          container.appendChild(div);
        });
      }).loadDataDynamic();
    }

    function deleteRecord(id) {
      google.script.run.withSuccessHandler(() => {
        loadData();
      }).removeData(id);
    }
  </script>

</body>
</html>
  `;

  return html;
}